-- GameTopUp KH initial PostgreSQL schema
-- Intended for a fresh PostgreSQL 17 database. Execute once; subsequent schema changes
-- should be handled with versioned migrations and reviewed production deployments.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Identity -----------------------------------------------------------
CREATE TABLE users (
                       id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                       full_name VARCHAR(150) NOT NULL,
                       email VARCHAR(255),
                       phone_number VARCHAR(20),
                       password_hash VARCHAR(255) NOT NULL,
                       account_status VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
                       email_verified BOOLEAN NOT NULL DEFAULT FALSE,
                       phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                       CONSTRAINT users_contact_required CHECK (NULLIF(btrim(email), '') IS NOT NULL OR NULLIF(btrim(phone_number), '') IS NOT NULL),
                       CONSTRAINT users_email_not_blank CHECK (email IS NULL OR btrim(email) <> ''),
                       CONSTRAINT users_phone_not_blank CHECK (phone_number IS NULL OR phone_number ~ '^\+[1-9][0-9]{1,14}$'),
    CONSTRAINT users_account_status_chk CHECK (account_status IN ('ACTIVE', 'SUSPENDED', 'DISABLED', 'PENDING_VERIFICATION'))
);
CREATE UNIQUE INDEX users_email_unique_ci ON users (lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX users_phone_number_unique ON users (phone_number) WHERE phone_number IS NOT NULL;

CREATE TABLE roles (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE user_roles (
                            user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                            role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
                            PRIMARY KEY (user_id, role_id)
);
CREATE INDEX idx_user_roles_role_id ON user_roles(role_id);

CREATE TABLE refresh_tokens (
                                id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                                user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                                token_hash VARCHAR(255) NOT NULL UNIQUE,
                                expires_at TIMESTAMPTZ NOT NULL,
                                revoked_at TIMESTAMPTZ,
                                created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens(user_id);
CREATE INDEX idx_refresh_tokens_expires_at ON refresh_tokens(expires_at);

-- Catalog ------------------------------------------------------------
CREATE TABLE games (
                       id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                       name VARCHAR(100) NOT NULL,
                       slug VARCHAR(120) NOT NULL UNIQUE,
                       player_id_label VARCHAR(100) NOT NULL DEFAULT 'Player ID',
                       requires_zone_id BOOLEAN NOT NULL DEFAULT FALSE,
                       is_active BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE game_packages (
                               id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                               game_id UUID NOT NULL REFERENCES games(id) ON DELETE RESTRICT,
                               name VARCHAR(150) NOT NULL,
                               sku VARCHAR(100) NOT NULL UNIQUE,
                               diamond_amount INTEGER NOT NULL CHECK (diamond_amount > 0),
                               price NUMERIC(12,2) NOT NULL CHECK (price > 0),
                               currency VARCHAR(3) NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_game_packages_game_active ON game_packages(game_id, is_active);

CREATE TABLE suppliers (
                           id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                           name VARCHAR(150) NOT NULL,
                           status VARCHAR(30) NOT NULL DEFAULT 'INACTIVE',
                           created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                           updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                           CONSTRAINT suppliers_status_chk CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED'))
);

CREATE TABLE supplier_products (
                                   id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                                   supplier_id UUID NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
                                   package_id UUID NOT NULL REFERENCES game_packages(id) ON DELETE RESTRICT,
                                   external_sku VARCHAR(150) NOT NULL,
                                   cost_price NUMERIC(12,2) NOT NULL CHECK (cost_price >= 0),
                                   currency VARCHAR(3) NOT NULL DEFAULT 'USD' CHECK (currency ~ '^[A-Z]{3}$'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_supplier_products_external_sku UNIQUE (supplier_id, external_sku)
);
CREATE INDEX idx_supplier_products_package_active ON supplier_products(package_id, is_active);

-- Orders -------------------------------------------------------------
CREATE TABLE orders (
                        id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                        order_number VARCHAR(50) NOT NULL UNIQUE,
                        user_id UUID REFERENCES users(id) ON DELETE SET NULL,
                        package_id UUID NOT NULL REFERENCES game_packages(id) ON DELETE RESTRICT,
                        player_id VARCHAR(100) NOT NULL,
                        zone_id VARCHAR(50),
                        contact_email VARCHAR(255),
                        contact_phone VARCHAR(20),
                        game_name_snapshot VARCHAR(100) NOT NULL,
                        package_name_snapshot VARCHAR(150) NOT NULL,
                        unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price > 0),
                        quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity = 1),
                        total_amount NUMERIC(12,2) NOT NULL CHECK (total_amount > 0),
                        currency VARCHAR(3) NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
    status VARCHAR(40) NOT NULL DEFAULT 'PENDING_PAYMENT',
    tracking_token_hash VARCHAR(255) UNIQUE,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT orders_price_chk CHECK (total_amount = unit_price * quantity),
    CONSTRAINT orders_player_id_not_blank CHECK (btrim(player_id) <> ''),
    CONSTRAINT orders_contact_phone_chk CHECK (contact_phone IS NULL OR contact_phone ~ '^\+[1-9][0-9]{1,14}$'),
    CONSTRAINT orders_status_chk CHECK (status IN ('PENDING_PAYMENT','PAID','PROCESSING','COMPLETED','FAILED','CANCELLED','REFUNDED','NEEDS_REVIEW'))
);
CREATE INDEX idx_orders_user_created ON orders(user_id, created_at DESC);
CREATE INDEX idx_orders_status_created ON orders(status, created_at DESC);
